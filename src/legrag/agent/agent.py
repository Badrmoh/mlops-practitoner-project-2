from typing import Any

from pydantic_ai import Agent

from legrag.agent.capabilities import legal_answer_guardrails, legal_retrieval_capability
from legrag.agent.schemas import LegalAnswer, RagDeps, RetrievedChunk


FORBIDDEN_META_PHRASES = (
    "retrieved context",
    "provided context",
    "based on the context",
    "based on the retrieved",
)


class LegalRagAgent:
    def __init__(
        self,
        model: Any,
        retriever,
        top_k: int = 5,
        distance_threshold: float | None = None,
    ) -> None:
        self._retriever = retriever
        self._top_k = top_k
        self._distance_threshold = distance_threshold
        self._agent = Agent(
            model,
            deps_type=RagDeps,
            output_type=LegalAnswer,
            instructions=(
                "You are a legal RAG assistant for the Egyptian Civil Code. "
                "Always call retrieve_legal_context with the user's question before answering. "
                "Use only chunks returned by that tool. "
                "If a retrieved article directly answers the question, answer using it. "
                "Answer only the exact question asked using the fewest necessary articles. "
                "Return only cited article numbers in cited_article_numbers; citation strings are generated by code."
            ),
            capabilities=[legal_retrieval_capability, legal_answer_guardrails],
        )

    def answer(self, question: str) -> LegalAnswer:
        deps = RagDeps(
            retriever=self._retriever,
            top_k=self._top_k,
            distance_threshold=self._distance_threshold,
        )
        result = self._agent.run_sync(question, deps=deps)
        answer = result.output
        answer.contexts = deps.retrieved_contexts
        self._normalize_answer(answer)
        self._validate_citations(answer)
        return answer

    def _normalize_answer(self, answer: LegalAnswer) -> None:
        retrieved_article_numbers: list[int] = []
        for chunk in answer.contexts:
            if chunk.article_number is not None and chunk.article_number not in retrieved_article_numbers:
                retrieved_article_numbers.append(chunk.article_number)

        answer.cited_article_numbers = [
            number for number in dict.fromkeys(answer.cited_article_numbers)
            if number in retrieved_article_numbers
        ]
        answer.citations = [self._format_citation(number) for number in answer.cited_article_numbers]

        if not answer.answered or not answer.cited_article_numbers:
            answer.answered = False
            answer.cited_article_numbers = []
            answer.citations = []
            return

        if any(phrase in answer.answer.casefold() for phrase in FORBIDDEN_META_PHRASES):
            for phrase in FORBIDDEN_META_PHRASES:
                answer.answer = answer.answer.replace(phrase, "").replace(phrase.title(), "")

        missing_in_text = [citation for citation in answer.citations if citation not in answer.answer]
        if missing_in_text:
            answer.answer = f"{answer.answer}\n\nCitations: {', '.join(answer.citations)}"

    def _validate_citations(self, answer: LegalAnswer) -> None:
        retrieved_article_numbers = {
            chunk.article_number for chunk in answer.contexts if chunk.article_number is not None
        }
        missing = [number for number in answer.cited_article_numbers if number not in retrieved_article_numbers]
        if missing:
            raise ValueError(f"Answer cited articles not present in retrieved context: {missing}")

    def _format_citation(self, article_number: int) -> str:
        return f"Egyptian Civil Code, Article {article_number}"
